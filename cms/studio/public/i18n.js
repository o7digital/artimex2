const storageKey = 'artimex-studio-language';
let locale = 'en';
try { if (globalThis.localStorage?.getItem(storageKey) === 'es') locale = 'es'; } catch { /* Storage may be disabled; English remains the default. */ }
export const getLocale = () => locale;
export const t = (source, language = locale) => language === 'es' ? source : (english[source] ?? source);

export function message(source) {
  const text = String(source ?? '');
  if (locale === 'es' || Object.hasOwn(english, text)) return t(text);
  const patterns = [
    [/^Valor inválido: (.+)\.$/, value => `Invalid value: ${value}.`],
    [/^Producto faltante antes de la fila (\d+)\.$/, row => `Missing product before row ${row}.`],
    [/^Nombre inválido en fila (\d+)\.$/, row => `Invalid name in row ${row}.`],
    [/^Fila (\d+): composición no reconocida\. No se importó nada\.$/, row => `Row ${row}: unrecognized composition. Nothing was imported.`],
    [/^Porcentaje o componente inválido en fila (\d+)\.$/, row => `Invalid percentage or component in row ${row}.`],
  ];
  for (const [pattern, format] of patterns) { const match = text.match(pattern); if (match) return format(...match.slice(1)); }
  return text;
}

export function initializeLanguage() {
  document.documentElement.lang = locale;
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  // These keys contain trusted, static interface markup from index.html.
  for (const element of document.querySelectorAll('[data-i18n-html]')) element.innerHTML = t(element.dataset.i18nHtml);
  for (const [data, attribute] of [['i18nAria', 'aria-label'], ['i18nPlaceholder', 'placeholder'], ['i18nAlt', 'alt']]) {
    for (const element of document.querySelectorAll(`[data-${data.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase())}]`)) element.setAttribute(attribute, t(element.dataset[data]));
  }
  for (const select of document.querySelectorAll('[data-language]')) {
    select.value = locale;
    select.addEventListener('change', () => {
      if (!['en', 'es'].includes(select.value) || select.value === locale) return;
      locale = select.value;
      try { globalThis.localStorage?.setItem(storageKey, locale); } catch { /* The selector still works when storage is unavailable. */ }
      // Keep the current route and authenticated cookie; rebuild translated labels and formatters.
      // A URL override also preserves the selection when local storage is disabled.
      const url = new URL(location.href); url.searchParams.set('lang', locale); location.replace(url);
    });
  }
}
